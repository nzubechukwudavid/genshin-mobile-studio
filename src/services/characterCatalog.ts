export async function fetchFullRoster(): Promise<CharacterEntry[]> {
  try {
    const metaRes = await fetch('/data/cache/characters_metadata.json');
    if (!metaRes.ok) return POPULAR_CHARACTERS;
    const metaData = await metaRes.json();
    
    // Try to load transparent artwork map if available
    let transparentsMap: Record<string, string> = {};
    try {
      const transRes = await fetch('/data/catalog/hoyo_transparents_catalog.json');
      if (transRes.ok) {
        const transJson = await transRes.json();
        for (const [charName, urls] of Object.entries(transJson)) {
          if (Array.isArray(urls) && urls.length > 0) {
            transparentsMap[charName] = urls[0];
          }
        }
      }
    } catch {
      // Fallback
    }

    const roster: CharacterEntry[] = [];
    for (const [name, info] of Object.entries(metaData as Record<string, any>)) {
      if (!info || !info.vision) continue;
      const element = (info.vision.charAt(0).toUpperCase() + info.vision.slice(1).toLowerCase()) as CharacterEntry['element'];
      const avatarUrl = info.icon || '';
      const artUrl = transparentsMap[name] || avatarUrl;

      roster.push({
        name,
        element: ['Pyro', 'Hydro', 'Anemo', 'Electro', 'Dendro', 'Cryo', 'Geo'].includes(element) ? element : 'Pyro',
        rarity: (info.rarity === 4 ? 4 : 5),
        weapon: info.weapon || 'Sword',
        avatarUrl,
        artUrl
      });
    }

    return roster.length > 0 ? roster : POPULAR_CHARACTERS;
  } catch (err) {
    console.warn('Falling back to popular characters catalog:', err);
    return POPULAR_CHARACTERS;
  }
}

